def bigrams(s: str) -> set[str]:
    s = norm(s)
    return {s[i:i + 2] for i in range(len(s) - 1)}


def main() -> int:
    qs = build()
    pages = {}
    for line in (ROOT / "data" / "processed_intermediate" / "pages.jsonl").read_text(encoding="utf-8").splitlines():
        if line.strip():
            p = json.loads(line)
            pages[(p["book_id"], p["page"])] = norm(p["text"])
    provided = [q for f in ("development.json", "additional.json") for q in json.loads((EVAL / f).read_text(encoding="utf-8"))]
    provided += json.loads((EXT / "hard_full.json").read_text(encoding="utf-8"))
    problems = []
    for q in qs:
        for grp in q["evidence_groups"]:
            for e in grp:
                if norm(e["quote"]) not in pages.get((e["book_id"], e["page"]), ""):
                    problems.append(f"{q['id']}: 근거 인용문이 {e['book_id']} p{e['page']}에 없음")
        sim = max(len(bigrams(q["question"]) & bigrams(p["question"])) / len(bigrams(q["question"]) | bigrams(p["question"])) for p in provided)
        q["_max_similarity_to_existing"] = round(sim, 3)
        if sim >= 0.6:
            problems.append(f"{q['id']}: 기존 질문과 유사도 {sim:.2f}")
    out = EXT / "cross_draft.json"
    if out.exists():
        print(f"이미 있습니다(덮어쓰지 않음): {out}. (중단)")
        return 1
    out.write_text(json.dumps(qs, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"저장: {out} ({len(qs)}개, dev {sum(q['split'] == 'dev' for q in qs)} / hold {sum(q['split'] == 'hold' for q in qs)})")
    print("검증 문제:", problems or "없음")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
